"""Retention (redops/retention.py) — bounded growth without losing evidence.

This is a red-team tool: the captures ARE the deliverable, so the policy is
deliberately narrow and DRY-RUN BY DEFAULT. Nothing here touches facts,
findings, evidence, credentials, principals, secrets, targets, services, sitrep,
objectives, leads or tool_runs. If you cannot explain why a row is disposable,
it does not get a category.

What IS disposable, measured on a real engagement (63k events, 34 MB):

  wire noise   flow + flowclose events — 44,675 rows / 2.6 MB, 70% of all event
               rows. Already excluded from the feed (`feed=1`) and from the
               report; they exist only to animate the live map, which cares
               about the last few minutes.
  closed flows rows in `flows` whose connection is long gone — the live map only
               draws recent ones (STALE_EST is 120s).
  dismissed    opportunities the operator already rejected — derived state,
  opportunities regenerated by correlate.run from the facts, which are kept.

Age is the guard, never the sole criterion: on a young engagement nothing is old
enough to prune, and that is the correct answer.
"""
from __future__ import annotations

from . import db

# Rows this module must never consider, stated positively so a future category
# has to argue with the list rather than quietly slip past it.
PROTECTED = ("facts", "findings", "evidence", "credentials", "principals",
             "secrets", "cred_bindings", "targets", "services", "sitrep",
             "objectives", "leads", "tool_runs", "entities", "payloads",
             "detection_rules", "poison", "engagements")

# event kinds that carry the narrative or the evidence — never pruned
KEEP_KINDS = ("action", "output", "reasoning", "note", "callback", "fact",
              "error", "objective")
WIRE_KINDS = ("flow", "flowclose")


def plan(conn, wire_days: float = 2, flow_days: float = 2, opp_days: float = 14,
         engagement_id=None) -> dict:
    """What WOULD be removed. Pure counting — no writes."""
    where_eng, p_eng = ("", [])
    if engagement_id is not None:
        where_eng, p_eng = " AND engagement_id=?", [engagement_id]

    q = ("SELECT count(*), COALESCE(sum(length(text)),0) FROM events "
         f"WHERE kind IN ({','.join('?' * len(WIRE_KINDS))}) "
         f"AND ts <= datetime('now', ?){where_eng}")
    wire_n, wire_b = conn.execute(q, [*WIRE_KINDS, f"-{wire_days} day", *p_eng]).fetchone()

    flow_n = conn.execute(
        "SELECT count(*) FROM flows WHERE state='closed' AND last_seen <= datetime('now', ?)"
        + where_eng, [f"-{flow_days} day", *p_eng]).fetchone()[0]

    opp_n = conn.execute(
        "SELECT count(*) FROM opportunities WHERE status='dismissed' "
        "AND updated_at <= datetime('now', ?)" + where_eng,
        [f"-{opp_days} day", *p_eng]).fetchone()[0]

    return {"wire_events": wire_n, "wire_bytes": wire_b,
            "closed_flows": flow_n, "dismissed_opportunities": opp_n,
            "total_rows": wire_n + flow_n + opp_n,
            "params": {"wire_days": wire_days, "flow_days": flow_days,
                       "opp_days": opp_days, "engagement_id": engagement_id}}


def prune(conn, wire_days: float = 2, flow_days: float = 2, opp_days: float = 14,
          engagement_id=None, apply: bool = False, vacuum: bool = True) -> dict:
    """Apply the plan. `apply=False` (the default) reports and changes nothing —
    deleting capture data is not something to do as a side effect of asking."""
    result = plan(conn, wire_days, flow_days, opp_days, engagement_id)
    result["applied"] = bool(apply)
    if not apply or not result["total_rows"]:
        return result

    where_eng, p_eng = ("", [])
    if engagement_id is not None:
        where_eng, p_eng = " AND engagement_id=?", [engagement_id]

    conn.execute(
        f"DELETE FROM events WHERE kind IN ({','.join('?' * len(WIRE_KINDS))}) "
        f"AND ts <= datetime('now', ?){where_eng}",
        [*WIRE_KINDS, f"-{wire_days} day", *p_eng])
    conn.execute(
        "DELETE FROM flows WHERE state='closed' AND last_seen <= datetime('now', ?)" + where_eng,
        [f"-{flow_days} day", *p_eng])
    conn.execute(
        "DELETE FROM opportunities WHERE status='dismissed' "
        "AND updated_at <= datetime('now', ?)" + where_eng,
        [f"-{opp_days} day", *p_eng])
    # orphaned link rows from the opportunities we just dropped
    conn.execute("DELETE FROM opportunity_facts WHERE opportunity_id NOT IN "
                 "(SELECT id FROM opportunities)")
    db.add_event(conn, "user", "note",
                 f"[retention] pruned {result['wire_events']:,} wire events, "
                 f"{result['closed_flows']:,} closed flows, "
                 f"{result['dismissed_opportunities']:,} dismissed opportunities",
                 engagement_id=engagement_id)
    conn.commit()
    if vacuum:
        # reclaim the file, not just the pages. VACUUM cannot run in a transaction.
        conn.isolation_level = None
        conn.execute("VACUUM")
    return result
